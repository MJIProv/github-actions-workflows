#!/usr/bin/env python3
"""Regenerate the hash-pinned requirements from PyPI.

Reads the pins from requirements.txt (single source of truth), then writes
requirements-all-platforms.txt. Run after changing a pin:

    python3 gen_hashes.py

Verify with `pip download --require-hashes` -- NOT `pip install --dry-run`,
which silently skips hash validation on an already-satisfied environment.
"""
import json, re, ssl, sys, urllib.request
from pathlib import Path

CA = "/root/.ccr/ca-bundle.crt"   # container-specific; falls back off-container
REQ = Path(__file__).with_name("requirements.txt")
OUT = Path(__file__).with_name("requirements-all-platforms.txt")


def ctx():
    try:
        return ssl.create_default_context(cafile=CA)
    except OSError:
        return ssl.create_default_context()


def read_pins(path=REQ):
    """Parse 'name==version' lines, ignoring comments. The only pin source."""
    pins = {}
    for line in path.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        m = re.fullmatch(r"([A-Za-z0-9._-]+)==([^\s;]+)", line)
        if m:
            pins[m.group(1).lower()] = m.group(2)
    if not pins:
        sys.exit(f"no 'name==version' pins found in {path}")
    return pins


def artifacts(pkg, ver):
    url = f"https://pypi.org/pypi/{pkg}/{ver}/json"
    with urllib.request.urlopen(url, context=ctx(), timeout=45) as r:
        d = json.load(r)
    return sorted((f["filename"], f["digests"]["sha256"]) for f in d["urls"])


def main():
    pins = read_pins()
    total = 0
    with OUT.open("w") as f:
        f.write("# Generated by gen_hashes.py from requirements.txt - do not hand-edit.\n")
        f.write("# pip install --require-hashes -r requirements-all-platforms.txt\n\n")
        for pkg, ver in pins.items():
            rows = artifacts(pkg, ver)
            f.write(f"# {pkg} {ver}: {len(rows)} artifacts\n{pkg}=={ver} \\\n")
            for i, (_n, dg) in enumerate(rows):
                f.write(f"    --hash=sha256:{dg}" + (" \\\n" if i < len(rows) - 1 else "\n"))
            f.write("\n")
            print(f"  {pkg}=={ver}: {len(rows)} hashes")
            total += len(rows)
    print(f"wrote {OUT.name}: {total} digests")


if __name__ == "__main__":
    main()
